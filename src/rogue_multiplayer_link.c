// Hashing
//

static u32 HashBytes(const void* data, u32 size)
{
    const u8* ptr = data;
    u32 hash = 0x811C9DC5;

    while(size--)
    {
        hash ^= *ptr++;
        hash *= 0x01000193;
    }

    return hash;
}

static u32 GetBuildFingerprint(void)
{
    // Both games must agree on the layout of everything that gets mirrored
    u32 values[] =
    {
        MPL_PROTOCOL_VERSION,
        sizeof(struct RogueNetPlayerProfile),
        sizeof(struct RogueNetPlayer),
        sizeof(struct RogueNetGameState),
        sizeof(struct Pokemon),
        NET_PLAYER_CAPACITY,
        ROGUE_SAVE_VERSION,
    };
    u32 hash = HashBytes(values, sizeof(values));
    u32 len = 0;

    while(gText_RogueVersion[len] != 0xFF && len < 16)
        ++len;

    return hash ^ HashBytes(gText_RogueVersion, len);
}

static bool8 IsExVersion(void)
{
#ifdef ROGUE_EXPANSION
    return TRUE;
#else
    return FALSE;
#endif
}

static bool8 IsPermaRevisedActive(void)
{
#ifdef ROGUE_FEATURE_REVISED_MODE
    if(Rogue_GetConfigRange(CONFIG_RANGE_REVISION_MODE) == REVISION_MODE_ALWAYS_ON)
        return TRUE;
#endif
    return FALSE;
}

// Region access
//

static u8 GetRemotePlayerId(void)
{
    return gRogueMultiplayer->localPlayerId == NET_PLAYER_ID_HOST ? 1 : NET_PLAYER_ID_HOST;
}

static bool8 IsRegionSentLocally(u8 region)
{
    if(region == MPL_REGION_GAME_STATE)
        return gRogueMPLink.isHost;

    return TRUE;
}

static bool8 IsRegionReceivedLocally(u8 region)
{
    if(region == MPL_REGION_GAME_STATE)
        return !gRogueMPLink.isHost;

    return TRUE;
}

static u16 GetRegionSize(u8 region)
{
    switch(region)
    {
    case MPL_REGION_PLAYER_STATE:
        return sizeof(struct RogueNetPlayer);
    case MPL_REGION_PROFILE:
        return sizeof(struct RogueNetPlayerProfile);
    default:
        return sizeof(struct RogueNetGameState);
    }
}

// What we send (our own copy)
static u8* GetLocalRegion(u8 region)
{
    switch(region)
    {
    case MPL_REGION_PLAYER_STATE:
        return (u8*)&gRogueMultiplayer->playerState[gRogueMultiplayer->localPlayerId];
    case MPL_REGION_PROFILE:
        return (u8*)&gRogueMultiplayer->playerProfiles[gRogueMultiplayer->localPlayerId];
    default:
        return (u8*)&gRogueMultiplayer->gameState;
    }
}

// Where the partner's copy lives
static u8* GetMirrorRegion(u8 region)
{
    switch(region)
    {
    case MPL_REGION_PLAYER_STATE:
        return (u8*)&gRogueMultiplayer->playerState[GetRemotePlayerId()];
    case MPL_REGION_PROFILE:
        return (u8*)&gRogueMultiplayer->playerProfiles[GetRemotePlayerId()];
    default:
        return (u8*)&gRogueMultiplayer->gameState;
    }
}

static u8* GetShadow(u8 region)
{
    switch(region)
    {
    case MPL_REGION_PLAYER_STATE:
        return sMPLinkBuffers.playerShadow;
    case MPL_REGION_PROFILE:
        return sMPLinkBuffers.profileShadow;
    default:
        return sMPLinkBuffers.game.tx.shadow;
    }
}

static u8* GetSnap(u8 region)
{
    switch(region)
    {
    case MPL_REGION_PLAYER_STATE:
        return sMPLinkBuffers.playerSnap;
    case MPL_REGION_PROFILE:
        return sMPLinkBuffers.profileSnap;
    default:
        return sMPLinkBuffers.game.tx.snap;
    }
}

static u8* GetStage(u8 region)
{
    switch(region)
    {
    case MPL_REGION_PLAYER_STATE:
        return sMPLinkBuffers.playerStage;
    case MPL_REGION_PROFILE:
        return sMPLinkBuffers.profileStage;
    default:
        return sMPLinkBuffers.game.rx.stage;
    }
}

static u32 HashMirrorRegion(u8 region)
{
    // The partner's profile flag is controlled locally by the connection state, so it's excluded
    if(region == MPL_REGION_PROFILE)
    {
        struct RogueNetPlayerProfile profile;
        memcpy(&profile, GetMirrorRegion(region), sizeof(profile));
        profile.isActive = TRUE;
        return HashBytes(&profile, sizeof(profile));
    }

    return HashBytes(GetMirrorRegion(region), GetRegionSize(region));
}

// Staging starts from our mirror, as the sender sees it
static void InitStageFromMirror(u8 region)
{
    memcpy(GetStage(region), GetMirrorRegion(region), GetRegionSize(region));

    if(region == MPL_REGION_PROFILE)
        ((struct RogueNetPlayerProfile*)GetStage(region))->isActive = TRUE;
}

static void ApplyStagedRegion(u8 region)
{
    memcpy(GetMirrorRegion(region), GetStage(region), GetRegionSize(region));

    if(region == MPL_REGION_PROFILE)
    {
        // Only show the partner once they're properly connected
        gRogueMultiplayer->playerProfiles[GetRemotePlayerId()].isActive = (gRogueMPLink.state == MPLINK_STATE_CONNECTED);
    }
}

static void ForceFullResend(u8 regionMask)
{
    u8 region;

    for(region = 0; region < MPL_REGION_COUNT; ++region)
    {
        if((regionMask & (1 << region)) && IsRegionSentLocally(region))
        {
            gRogueMPLink.tx[region].forceFull = TRUE;
            gRogueMPLink.tx[region].inTxn = FALSE;
        }
    }
}

static void ResetRxState(void)
{
    gRogueMPLink.rxSeqValid = FALSE;
    gRogueMPLink.rxInTxn = 0;
    gRogueMPLink.rxCommitted = 0;
    gRogueMPLink.pendingResyncRequest = 0;
}

static void ResetTxState(void)
{
    memset(gRogueMPLink.tx, 0, sizeof(gRogueMPLink.tx));
    gRogueMPLink.nextRegion = 0;
    gRogueMPLink.digestRegion = 0;
    gRogueMPLink.idleTimer = 0;
}

static void RequestResync(u8 regionMask)
{
    u8 region;

    for(region = 0; region < MPL_REGION_COUNT; ++region)
    {
        if(regionMask & (1 << region))
            gRogueMPLink.rxInTxn &= ~(1 << region);
    }

    gRogueMPLink.pendingResyncRequest |= regionMask;
}

// Messages
//

static void WriteU32(u16* dst, u32 value)
{
    dst[0] = value & 0xFFFF;
    dst[1] = value >> 16;
}

static u32 ReadU32(const u16* src)
{
    return src[0] | ((u32)src[1] << 16);
}

static void BeginMessage(u8 type, u8 arg)
{
    u8 i;

    for(i = 0; i < CMD_LENGTH; ++i)
        gSendCmd[i] = 0;

    gSendCmd[0] = MPL_MSG_BASE | type;
    ++gRogueMPLink.stats.msgsSent;
    gSendCmd[1] = gRogueMPLink.txSeq++ | (arg << 8);
}

static void SendHello(void)
{
    u8 flags = 0;

    if(gRogueMPLink.isHost)
        flags |= HELLO_FLAG_IS_HOST;
    if(IsExVersion())
        flags |= HELLO_FLAG_IS_EX;
    if(IsPermaRevisedActive())
        flags |= HELLO_FLAG_PERMA_REVISED;

    BeginMessage(MPL_MSG_HELLO, 0);
    gSendCmd[2] = MPL_PROTOCOL_VERSION | (flags << 8);
    gSendCmd[3] = RogueSave_GetVersionId();
    WriteU32(&gSendCmd[4], GetBuildFingerprint());
    WriteU32(&gSendCmd[6], gRogueMPLink.helloNonce);
}

static bool8 TrySendRegionMessage(void)
{
    u8 i;

    for(i = 0; i < MPL_REGION_COUNT; ++i)
    {
        u8 region = (gRogueMPLink.nextRegion + i) % MPL_REGION_COUNT;
        struct MPLinkTx* tx = &gRogueMPLink.tx[region];
        u16 size = GetRegionSize(region);
        u8* shadow;
        u8* snap;

        if(!IsRegionSentLocally(region))
            continue;

        shadow = GetShadow(region);
        snap = GetSnap(region);

        if(!tx->inTxn)
        {
            u8* local = GetLocalRegion(region);

            if(!tx->forceFull && memcmp(local, shadow, size) == 0)
                continue;

            // Start a new transaction from a consistent snapshot
            memcpy(snap, local, size);
            tx->inTxn = TRUE;
            tx->cursor = 0;
        }

        // Send the next changed chunk
        while(tx->cursor < size)
        {
            u16 offset = tx->cursor;
            u16 len = min(MPL_CHUNK_BYTES, size - offset);

            tx->cursor += len;

            if(tx->forceFull || memcmp(snap + offset, shadow + offset, len) != 0)
            {
                u8 chunk[MPL_CHUNK_BYTES] = {0};

                memcpy(chunk, snap + offset, len);
                memcpy(shadow + offset, snap + offset, len);

                BeginMessage(MPL_MSG_CHUNK, region);
                gSendCmd[2] = offset;
                memcpy(&gSendCmd[3], chunk, MPL_CHUNK_BYTES);
                return TRUE;
            }
        }

        // Everything sent, commit it
        BeginMessage(MPL_MSG_COMMIT, region);
        gSendCmd[2] = size;
        WriteU32(&gSendCmd[3], HashBytes(snap, size));
        gSendCmd[5] = tx->txnId++;

        tx->inTxn = FALSE;
        tx->forceFull = FALSE;
        gRogueMPLink.nextRegion = (region + 1) % MPL_REGION_COUNT;
        return TRUE;
    }

    return FALSE;
}

static void SendIdleDigest(void)
{
    u8 i;

    // Rotate through the regions we own so the partner can verify their mirror
    for(i = 0; i < MPL_REGION_COUNT; ++i)
    {
        u8 region = (gRogueMPLink.digestRegion + i) % MPL_REGION_COUNT;

        if(IsRegionSentLocally(region))
        {
            u16 size = GetRegionSize(region);

            gRogueMPLink.digestRegion = (region + 1) % MPL_REGION_COUNT;

            BeginMessage(MPL_MSG_DIGEST, region);
            gSendCmd[2] = size;
            WriteU32(&gSendCmd[3], HashBytes(GetShadow(region), size));
            return;
        }
    }
}

static void BuildOutgoingMessage(void)
{
    switch(gRogueMPLink.state)
    {
    case MPLINK_STATE_HELLO:
        if(gRogueMPLink.isHost && gRogueMPLink.pendingWelcomeResult != 0xFF)
        {
            BeginMessage(MPL_MSG_WELCOME, gRogueMPLink.pendingWelcomeResult);
            gSendCmd[2] = 1; // assigned player id
            WriteU32(&gSendCmd[4], gRogueMPLink.sessionId);
            WriteU32(&gSendCmd[6], gRogueMPLink.acceptedNonce);

            if(gRogueMPLink.pendingWelcomeResult == CONN_ERR_NONE)
            {
                gRogueMPLink.sentWelcome = TRUE;
                gRogueMPLink.state = MPLINK_STATE_SYNCING;
                gRogueMPLink.stateTimer = 0;
            }

            gRogueMPLink.pendingWelcomeResult = 0xFF;
            return;
        }

        if((gRogueMPLink.stateTimer % MPL_HELLO_INTERVAL) == 0)
            SendHello();
        return;

    case MPLINK_STATE_SYNCING:
    case MPLINK_STATE_CONNECTED:
        if(gRogueMPLink.pendingResyncRequest != 0)
        {
            BeginMessage(MPL_MSG_RESYNC, gRogueMPLink.pendingResyncRequest);
            ++gRogueMPLink.stats.resyncRequestsSent;
            gRogueMPLink.pendingResyncRequest = 0;
            return;
        }

        if(TrySendRegionMessage())
        {
            gRogueMPLink.idleTimer = 0;
            return;
        }

        if(++gRogueMPLink.idleTimer >= MPL_IDLE_INTERVAL)
        {
            gRogueMPLink.idleTimer = 0;
            SendIdleDigest();
        }
        return;
    }
}

static u8 ValidateHello(const u16* cmd)
{
    u8 proto = cmd[2] & 0xFF;
    u8 flags = cmd[2] >> 8;

    if(proto != MPL_PROTOCOL_VERSION || ReadU32(&cmd[4]) != GetBuildFingerprint())
        return CONN_ERR_WRONG_BUILD;

    if(((flags & HELLO_FLAG_IS_EX) != 0) != IsExVersion())
        return CONN_ERR_WRONG_GAME_FLAVOUR;

    if(cmd[3] != RogueSave_GetVersionId())
        return CONN_ERR_WRONG_SAVE_VERSION;

    if(((flags & HELLO_FLAG_PERMA_REVISED) != 0) != IsPermaRevisedActive())
        return CONN_ERR_WRONG_REVISED_MODE;

    if(((flags & HELLO_FLAG_IS_HOST) != 0) == gRogueMPLink.isHost)
        return CONN_ERR_SAME_ROLE;

    return CONN_ERR_NONE;
}

static void FailSession(u8 reason)
{
    MpLinkLogf("Session failed reason:%d", reason);
    gRogueMPLink.failReason = reason;
}

static void HandleHello(const u16* cmd)
{
    u8 result = ValidateHello(cmd);
    u32 nonce = ReadU32(&cmd[6]);

    if(gRogueMPLink.isHost)
    {
        if(gRogueMPLink.state != MPLINK_STATE_HELLO)
        {
            // HELLOs still in flight from the attempt we already accepted
            if(gRogueMPLink.helloAccepted && nonce == gRogueMPLink.acceptedNonce)
                return;

            // Partner restarted their connection attempt; start the handshake again
            if(result != CONN_ERR_NONE)
                return;

            MpLinkLog("Partner restarted handshake");
            gRogueMPLink.state = MPLINK_STATE_HELLO;
            gRogueMPLink.stateTimer = 0;
            gRogueMPLink.helloAccepted = FALSE;
            gRogueMPLink.sentWelcome = FALSE;
            SetPartnerVisible(FALSE);
        }

        if(!gRogueMPLink.helloAccepted || nonce != gRogueMPLink.acceptedNonce)
        {
            gRogueMPLink.pendingWelcomeResult = result;

            if(result == CONN_ERR_NONE)
            {
                gRogueMPLink.helloAccepted = TRUE;
                gRogueMPLink.acceptedNonce = nonce;
                ResetRxState();
                ResetTxState();
                ForceFullResend(MPL_REGION_MASK_ALL);
            }
        }
    }
    else
    {
        // Host checks too, but report problems found on our side straight away
        if(result != CONN_ERR_NONE && result != CONN_ERR_SAME_ROLE)
            FailSession(result);
        else if(result == CONN_ERR_SAME_ROLE)
            FailSession(CONN_ERR_SAME_ROLE);
    }
}

static void HandleWelcome(const u16* cmd)
{
    u8 result = cmd[1] >> 8;
    u32 sessionId = ReadU32(&cmd[4]);

    if(gRogueMPLink.isHost || gRogueMPLink.state != MPLINK_STATE_HELLO)
        return;

    // WELCOME for an older attempt
    if(ReadU32(&cmd[6]) != gRogueMPLink.helloNonce)
        return;

    if(result != CONN_ERR_NONE)
    {
        FailSession(result);
        return;
    }

    if(gRogueMPLink.hasEverConnected && gRogueMPLink.sessionId != sessionId && Rogue_IsRunActive())
    {
        // Host restarted; we can only carry on if they're on the same adventure (checked once synced)
        MpLinkLogf("Joining new session %x (was %x)", sessionId, gRogueMPLink.sessionId);
    }

    gRogueMPLink.sessionId = sessionId;
    gRogueMPLink.helloAccepted = TRUE;
    gRogueMultiplayer->localPlayerId = cmd[2];

    ResetRxState();
    ResetTxState();
    ForceFullResend(MPL_REGION_MASK_ALL);

    gRogueMPLink.state = MPLINK_STATE_SYNCING;
    gRogueMPLink.stateTimer = 0;
}

static void HandleChunk(const u16* cmd)
{
    u8 region = cmd[1] >> 8;
    u16 offset = cmd[2];
    u16 size;
    u16 len;
    u8* stage;

    if(region >= MPL_REGION_COUNT || !IsRegionReceivedLocally(region))
        return;

    size = GetRegionSize(region);
    if(offset >= size)
        return;

    stage = GetStage(region);

    if(!(gRogueMPLink.rxInTxn & (1 << region)))
    {
        // New transaction starts from what we currently have
        InitStageFromMirror(region);
        gRogueMPLink.rxInTxn |= (1 << region);
    }

    len = min(MPL_CHUNK_BYTES, size - offset);
    memcpy(stage + offset, &cmd[3], len);
}

static void HandleCommit(const u16* cmd)
{
    u8 region = cmd[1] >> 8;
    u32 hash = ReadU32(&cmd[3]);
    u16 size;
    u8* stage;

    if(region >= MPL_REGION_COUNT || !IsRegionReceivedLocally(region))
        return;

    size = GetRegionSize(region);
    stage = GetStage(region);

    if(cmd[2] != size)
    {
        RequestResync(1 << region);
        return;
    }

    if(!(gRogueMPLink.rxInTxn & (1 << region)))
    {
        // Empty transaction (nothing changed since our copy)
        InitStageFromMirror(region);
    }

    gRogueMPLink.rxInTxn &= ~(1 << region);

    if(HashBytes(stage, size) != hash)
    {
        MpLinkLogf("Region %d hash mismatch, requesting resync", region);
        ++gRogueMPLink.stats.hashMismatches;
        RequestResync(1 << region);
        return;
    }

    gRogueMPLink.rxCommitted |= (1 << region);
    ApplyStagedRegion(region);
}

static void HandleDigest(const u16* cmd)
{
    u8 region = cmd[1] >> 8;

    if(region >= MPL_REGION_COUNT || !IsRegionReceivedLocally(region))
        return;

    // Only meaningful for regions we have fully received and aren't mid way through updating
    if(!(gRogueMPLink.rxCommitted & (1 << region)) || (gRogueMPLink.rxInTxn & (1 << region)))
        return;

    if(cmd[2] != GetRegionSize(region) || HashMirrorRegion(region) != ReadU32(&cmd[3]))
    {
        MpLinkLogf("Region %d digest mismatch, requesting resync", region);
        ++gRogueMPLink.stats.digestMismatches;
        RequestResync(1 << region);
    }
}

static void HandleIncomingMessage(const u16* cmd)
{
    u8 type = cmd[0] & 0xFF;
    u8 seq = cmd[1] & 0xFF;

    if((cmd[0] & MPL_MSG_MASK) != MPL_MSG_BASE)
        return;

    gRogueMPLink.framesSinceRecv = 0;
    ++gRogueMPLink.stats.msgsRecv;

    // Detect dropped messages
    if(gRogueMPLink.rxSeqValid && seq != (u8)(gRogueMPLink.rxSeq + 1))
    {
        ++gRogueMPLink.stats.seqGaps;
        MpLinkLogf("Seq gap %d -> %d, requesting resync", gRogueMPLink.rxSeq, seq);
        if(gRogueMPLink.state == MPLINK_STATE_SYNCING || gRogueMPLink.state == MPLINK_STATE_CONNECTED)
            RequestResync(MPL_REGION_MASK_ALL);
    }
    gRogueMPLink.rxSeq = seq;
    gRogueMPLink.rxSeqValid = TRUE;

    switch(type)
    {
    case MPL_MSG_HELLO:
        HandleHello(cmd);
        break;

    case MPL_MSG_WELCOME:
        HandleWelcome(cmd);
        break;

    case MPL_MSG_CHUNK:
        if(gRogueMPLink.state == MPLINK_STATE_SYNCING || gRogueMPLink.state == MPLINK_STATE_CONNECTED)
            HandleChunk(cmd);
        break;

    case MPL_MSG_COMMIT:
        if(gRogueMPLink.state == MPLINK_STATE_SYNCING || gRogueMPLink.state == MPLINK_STATE_CONNECTED)
            HandleCommit(cmd);
        break;

    case MPL_MSG_DIGEST:
        if(gRogueMPLink.state == MPLINK_STATE_CONNECTED)
            HandleDigest(cmd);
        break;

    case MPL_MSG_RESYNC:
        if(gRogueMPLink.state == MPLINK_STATE_SYNCING || gRogueMPLink.state == MPLINK_STATE_CONNECTED)
        {
            ++gRogueMPLink.stats.resyncRequestsRecv;
            ForceFullResend(cmd[1] >> 8);
        }
        break;

    case MPL_MSG_BYE:
        MpLinkLog("Partner said bye");
        if(gRogueMPLink.isHost)
            OnPartnerLost(MPL_LOSS_BYE);
        else
            FailSession(CONN_ERR_LOST_HOST);
        break;
    }
}

// Runs inside the link layer every frame the cable connection is established
static void LinkCB_RogueMP(void)
{
    u8 i;

    if(gRogueMultiplayer == NULL || gRogueMPLink.state == MPLINK_STATE_OFF)
        return;

    // The link layer checksums every 9 word block and closes the link on a mismatch. Under emulator
    // netplay a block is occasionally corrupted without the link being broken. Every message here is
    // sequenced and hashed (corruption shows up as a gap or mismatch and gets resynced), so ride over
    // isolated checksum errors instead of dropping the partner. A burst of them (e.g. the two ends
    // fell out of step) still closes the link.
    if((gLinkStatus & LINK_STAT_ERRORS) == LINK_STAT_ERROR_CHECKSUM
    && gRogueMPLink.checksumErrorLoad + MPL_CHECKSUM_ERROR_COST <= MPL_CHECKSUM_ERROR_LIMIT)
    {
        gLink.badChecksum = FALSE;
        gLinkStatus &= ~LINK_STAT_ERROR_CHECKSUM;
        gRogueMPLink.checksumErrorLoad += MPL_CHECKSUM_ERROR_COST;

        if(gRogueMPLink.checksumErrors != 0xFF)
            ++gRogueMPLink.checksumErrors;
    }

    // Runs just before the link layer reacts to errors (and closes itself), so remember them
    if(gLinkStatus & LINK_STAT_ERRORS)
        gRogueMPLink.lastLinkErrors = (gLinkStatus & LINK_STAT_ERRORS) >> LINK_STAT_ERRORS_SHIFT;

    for(i = 0; i < MAX_LINK_PLAYERS; ++i)
    {
        if(i == SIO_MULTI_CNT->id)
            continue;

        if(gRecvCmds[i][0] != 0)
            HandleIncomingMessage(gRecvCmds[i]);
    }

    BuildOutgoingMessage();
}

// Session management
//

static void OpenCableLink(void)
{
    gLinkType = LINKTYPE_TRADE;
    OpenLink();

    // Don't run the vanilla player exchange, and never show the vanilla "communication error" screen
    gLinkCallback = LinkCB_RogueMP;
    SetSuppressLinkErrorMessage(TRUE);

    gRogueMPLink.linkOpen = TRUE;
    gRogueMPLink.helloAccepted = FALSE;
    gRogueMPLink.acceptedNonce = 0;

    do
    {
        gRogueMPLink.helloNonce = Random32();
    }
    while(gRogueMPLink.helloNonce == 0);

    gRogueMPLink.sentWelcome = FALSE;
    gRogueMPLink.pendingWelcomeResult = 0xFF;
    gRogueMPLink.framesSinceRecv = 0;
    gRogueMPLink.checksumErrorLoad = 0;
    ResetRxState();
    ResetTxState();
}

static void CloseCableLink(void)
{
    if(gRogueMPLink.linkOpen)
    {
        CloseLink();
        gLinkCallback = NULL;
        gRogueMPLink.linkOpen = FALSE;
    }

    // Tasks spawned by OpenLink
    gShouldAdvanceLinkState = 0;
}

static void SetPartnerVisible(bool8 visible)
{
    if(gRogueMultiplayer != NULL)
        gRogueMultiplayer->playerProfiles[GetRemotePlayerId()].isActive = visible;
}

static void OnPartnerLost(u8 reason)
{
    MpLinkLogf("Partner lost reason:%d errors:%x", reason, gRogueMPLink.lastLinkErrors);
    gRogueMPLink.lastLossReason = reason;

    if(gRogueMPLink.state == MPLINK_STATE_CONNECTED)
        Rogue_PushPopup_MultiplayerPartnerLost();

    SetPartnerVisible(FALSE);
    CloseCableLink();

    gRogueMPLink.state = MPLINK_STATE_RECONNECTING;
    gRogueMPLink.stateTimer = 0;
    ++gRogueMPLink.stats.reconnects;
}

static void AdvanceCableHandshake(void)
{
    // The vanilla link waits for scripts to poke it along (e.g. the cable club receptionist), do it here instead
    if(gLink.state == LINK_STATE_START1)
    {
        gShouldAdvanceLinkState = 1;
    }
    else if(gLink.state == LINK_STATE_HANDSHAKE && (gRogueMPLink.stateTimer % 8) == 0)
    {
        if(gLink.isMaster == LINK_MASTER && gLink.playerCount > 1)
            gShouldAdvanceLinkState = 1;
    }
}

static u8 GetCableLossReason(void)
{
    if(HasLinkErrorOccurred())
        return MPL_LOSS_LINK_ERROR;
    if(!IsLinkConnectionEstablished())
        return MPL_LOSS_LINK_DOWN;
    if(EXTRACT_PLAYER_COUNT(gLinkStatus) < 2)
        return MPL_LOSS_PLAYER_COUNT;
    return MPL_LOSS_TIMEOUT;
}

static bool8 IsCableLinkUp(void)
{
    return !HasLinkErrorOccurred() && IsLinkConnectionEstablished() && EXTRACT_PLAYER_COUNT(gLinkStatus) >= 2;
}

static bool8 CheckRejoinAllowed(void)
{
    // A client in the middle of an adventure can only rejoin the same adventure, otherwise both games
    // would be running different maps/encounters while pretending to be together
    if(!gRogueMPLink.isHost && Rogue_IsRunActive())
    {
        if(!gRogueMultiplayer->gameState.adventure.isRunActive)
            return FALSE;

        if(gRogueMultiplayer->gameState.adventure.baseSeed != (u16)gRogueRun.baseSeed)
            return FALSE;
    }

    return TRUE;
}

void RogueMPLink_Start(bool8 asHost)
{
    memset(&gRogueMPLink, 0, sizeof(gRogueMPLink));

    gRogueMPLink.isHost = asHost;
    gRogueMPLink.state = MPLINK_STATE_LINKING;
    gRogueMPLink.failReason = CONN_ERR_NONE;
    gRogueMPLink.pendingWelcomeResult = 0xFF;

    if(asHost)
    {
        do
        {
            gRogueMPLink.sessionId = Random32();
        }
        while(gRogueMPLink.sessionId == 0);
    }

    OpenCableLink();
}

void RogueMPLink_Stop(void)
{
    CloseCableLink();
    gRogueMPLink.state = MPLINK_STATE_OFF;
}

u8 RogueMPLink_GetState(void)
{
    return gRogueMPLink.state;
}

bool8 RogueMPLink_IsPartnerConnected(void)
{
    return gRogueMPLink.state == MPLINK_STATE_CONNECTED;
}

bool8 RogueMPLink_HasJoinedSession(void)
{
    return gRogueMPLink.hasEverConnected;
}

u8 RogueMPLink_GetFailReason(void)
{
    return gRogueMPLink.failReason;
}

void RogueMPLink_ClearFailReason(void)
{
    gRogueMPLink.failReason = CONN_ERR_NONE;
}

void RogueMPLink_Update(void)
{
    if(gRogueMultiplayer == NULL || gRogueMPLink.state == MPLINK_STATE_OFF)
        return;

    ++gRogueMPLink.stateTimer;

    if(gRogueMPLink.checksumErrorLoad != 0)
        --gRogueMPLink.checksumErrorLoad;

    if(gRogueMPLink.linkOpen && gRogueMPLink.framesSinceRecv < 0xFFFF)
        ++gRogueMPLink.framesSinceRecv;

    switch(gRogueMPLink.state)
    {
    case MPLINK_STATE_LINKING:
        if(HasLinkErrorOccurred())
        {
            CloseCableLink();
            gRogueMPLink.state = MPLINK_STATE_RECONNECTING;
            gRogueMPLink.stateTimer = 0;
        }
        else if(IsCableLinkUp())
        {
            MpLinkLogf("Cable link up (master:%d)", gLink.isMaster == LINK_MASTER);
            gRogueMPLink.state = MPLINK_STATE_HELLO;
            gRogueMPLink.stateTimer = 0;
            gRogueMPLink.framesSinceRecv = 0;
        }
        else
        {
            AdvanceCableHandshake();

            if(gRogueMPLink.stateTimer >= MPL_LINKING_RETRY_FRAMES && gRogueMPLink.hasEverConnected)
            {
                // Handshake stalled, start again
                CloseCableLink();
                gRogueMPLink.state = MPLINK_STATE_RECONNECTING;
                gRogueMPLink.stateTimer = 0;
            }
        }
        break;

    case MPLINK_STATE_HELLO:
    case MPLINK_STATE_SYNCING:
        if(!IsCableLinkUp() || gRogueMPLink.framesSinceRecv >= MPL_TIMEOUT_FRAMES)
        {
            OnPartnerLost(GetCableLossReason());
        }
        else if(gRogueMPLink.state == MPLINK_STATE_SYNCING)
        {
            u8 required = (1 << MPL_REGION_PLAYER_STATE) | (1 << MPL_REGION_PROFILE);

            if(!gRogueMPLink.isHost)
                required |= (1 << MPL_REGION_GAME_STATE);

            if((gRogueMPLink.rxCommitted & required) == required)
            {
                if(!CheckRejoinAllowed())
                {
                    FailSession(CONN_ERR_DIFFERENT_ADVENTURE);
                    break;
                }

                MpLinkLog("Partner synced");
                gRogueMPLink.state = MPLINK_STATE_CONNECTED;
                gRogueMPLink.stateTimer = 0;
                SetPartnerVisible(TRUE);

                if(gRogueMPLink.hasEverConnected)
                    Rogue_PushPopup_MultiplayerPartnerRejoined();
                else
                    Rogue_PushPopup_MultiplayerPartnerJoined();

                gRogueMPLink.hasEverConnected = TRUE;
                gRogueMPLink.lostTimer = 0;
            }
        }
        break;

    case MPLINK_STATE_CONNECTED:
        if(!IsCableLinkUp() || gRogueMPLink.framesSinceRecv >= MPL_TIMEOUT_FRAMES)
            OnPartnerLost(GetCableLossReason());
        else if(!CheckRejoinAllowed())
            FailSession(CONN_ERR_DIFFERENT_ADVENTURE);
        break;

    case MPLINK_STATE_RECONNECTING:
        if(!gRogueMPLink.isHost && gRogueMPLink.hasEverConnected)
        {
            if(++gRogueMPLink.lostTimer >= MPL_CLIENT_GIVE_UP_FRAMES)
            {
                FailSession(CONN_ERR_LOST_HOST);
                break;
            }
        }

        if(gRogueMPLink.stateTimer >= MPL_REOPEN_DELAY_FRAMES)
        {
            MpLinkLog("Reopening link");
            OpenCableLink();
            gRogueMPLink.state = MPLINK_STATE_LINKING;
            gRogueMPLink.stateTimer = 0;
        }
        break;
    }
}
