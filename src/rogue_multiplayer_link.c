// Link cable transport for Rogue multiplayer (2 players).
//
// Both games keep a mirror of the other player's data in gRogueMultiplayer (as they did when the
// Rogue Assistant copied memory between emulators). Here that copying is done over the link cable:
//
//  - Each side replicates "regions" it owns: its profile, its player state and (host only) the
//    shared game state (hub, difficulty, time, adventure seed).
//  - A region update is a transaction: changed 10 byte chunks followed by a COMMIT carrying a hash
//    of the whole region. The receiver stages chunks and only applies them when the hash matches,
//    so the mirror never holds a half written state.
//  - Messages carry a sequence number. Any gap, hash mismatch or periodic DIGEST mismatch makes the
//    receiver ask for a full resend of the affected regions, so the mirrors heal themselves.
//  - If nothing is heard from the partner for a while (or the link errors), the link is torn down
//    and reopened. The partner can rejoin the same session; when rejoining an adventure the run seed
//    must match the host's.
//
// The cable layer sends one 8 halfword command per frame per player. Emulators relaying the link
// over the network (gpSP "Pokemon Gen3 mode") only transmit non-zero commands, reliably and in order.

#define MPL_PROTOCOL_VERSION    1

#if 1
#define MpLinkLog(pBuf) DebugPrint("[MP LINK] " pBuf)
#define MpLinkLogf(pBuf, ...) DebugPrintf("[MP LINK] " pBuf, __VA_ARGS__)
#else
#define MpLinkLog(pBuf)
#define MpLinkLogf(pBuf, ...)
#endif

#define MPL_MSG_BASE            0x3A00 // unused by vanilla LINKCMD_* values
#define MPL_MSG_MASK            0xFF00

enum
{
    MPL_MSG_HELLO = 1,
    MPL_MSG_WELCOME,
    MPL_MSG_CHUNK,
    MPL_MSG_COMMIT,
    MPL_MSG_DIGEST,
    MPL_MSG_RESYNC,
    MPL_MSG_BYE,
    MPL_MSG_PING,
};

enum
{
    MPL_REGION_PLAYER_STATE,
    MPL_REGION_PROFILE,
    MPL_REGION_GAME_STATE,
    MPL_REGION_COUNT,
};

#define MPL_REGION_MASK_ALL         ((1 << MPL_REGION_COUNT) - 1)

#define MPL_CHUNK_BYTES             10
#define MPL_HELLO_INTERVAL          15      // frames between HELLO repeats
#define MPL_IDLE_INTERVAL           20      // frames between keep alive digests
#define MPL_CHECKSUM_ERROR_COST     60      // see LinkCB_RogueMP
#define MPL_CHECKSUM_ERROR_LIMIT    300
#define MPL_TIMEOUT_FRAMES          (60 * 4)    // partner considered lost after 4s of silence
#define MPL_REOPEN_DELAY_FRAMES     60
#define MPL_LINKING_RETRY_FRAMES    (60 * 10)   // reopen the link if a handshake stalls
#define MPL_CLIENT_GIVE_UP_FRAMES   (60 * 120)  // client stops trying to rejoin after 2 minutes

enum
{
    MPL_LOSS_NONE,
    MPL_LOSS_LINK_ERROR,
    MPL_LOSS_LINK_DOWN,
    MPL_LOSS_PLAYER_COUNT,
    MPL_LOSS_TIMEOUT,
    MPL_LOSS_BYE,
};

#define HELLO_FLAG_IS_HOST          (1 << 0)
#define HELLO_FLAG_IS_EX            (1 << 1)
#define HELLO_FLAG_PERMA_REVISED    (1 << 2)

STATIC_ASSERT(NET_PLAYER_CAPACITY == 2, LinkTransportIs2Players);

struct MPLinkTx
{
    u16 cursor;
    u8 inTxn : 1;
    u8 forceFull : 1;
    u8 txnId;
};

// Kept first so tools can read them at fixed offsets (see tools/netplay_harness)
struct MPLinkStats
{
    u16 seqGaps;
    u16 hashMismatches;
    u16 digestMismatches;
    u16 resyncRequestsSent;
    u16 resyncRequestsRecv;
    u16 reconnects;
    u16 msgsRecv;
    u16 msgsSent;
};

struct MPLinkSession
{
    struct MPLinkStats stats;
    u8 state;
    u8 lastLossReason;  // MPL_LOSS_* (diagnostics)
    u8 lastLinkErrors;  // LINK_STAT_ERRORS bits seen by the link layer before it closed
    u8 checksumErrors;  // link layer checksum errors that were ridden over (diagnostics)
    u32 sessionId;          // generated by host
    u32 helloNonce;         // random per connection attempt, echoed back in WELCOME
    u32 acceptedNonce;      // host: nonce of the HELLO that was accepted
    u16 stateTimer;
    u16 framesSinceRecv;
    u16 lostTimer;
    u16 idleTimer;
    u16 checksumErrorLoad;
    u8 isHost : 1;
    u8 linkOpen : 1;
    u8 helloAccepted : 1;   // host: partner HELLO validated / client: WELCOME received
    u8 sentWelcome : 1;
    u8 rxSeqValid : 1;
    u8 hasEverConnected : 1;
    u8 txSeq;
    u8 rxSeq;
    u8 pendingResyncRequest; // regions we want the partner to resend
    u8 rxCommitted;          // regions received at least once since (re)connecting
    u8 rxInTxn;              // regions with a transaction being staged
    u8 nextRegion;
    u8 digestRegion;
    u8 failReason;
    u8 pendingWelcomeResult;
    struct MPLinkTx tx[MPL_REGION_COUNT];
};

// Region buffers. The game state is only ever sent by the host and received by the client, so its
// tx and rx buffers can share memory.
struct MPLinkBuffers
{
    u8 profileShadow[sizeof(struct RogueNetPlayerProfile)];
    u8 profileSnap[sizeof(struct RogueNetPlayerProfile)];
    u8 profileStage[sizeof(struct RogueNetPlayerProfile)];
    u8 playerShadow[sizeof(struct RogueNetPlayer)];
    u8 playerSnap[sizeof(struct RogueNetPlayer)];
    u8 playerStage[sizeof(struct RogueNetPlayer)];
    union
    {
        struct
        {
            u8 shadow[sizeof(struct RogueNetGameState)];
            u8 snap[sizeof(struct RogueNetGameState)];
        } tx;
        struct
        {
            u8 stage[sizeof(struct RogueNetGameState)];
        } rx;
    } game;
};

